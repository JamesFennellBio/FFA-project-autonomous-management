#!/usr/bin/env bash
# Rebuilds the "Every CRYPTO-REVIEW location" index at the bottom of
# docs/CRYPTO_REVIEW.md from the `CRYPTO-REVIEW` tags in the source.
#
#   ./scripts/crypto-review.sh          # update the doc
#   ./scripts/crypto-review.sh --check  # CI: fail if the doc is out of date
set -euo pipefail
# Same sort order everywhere (CI and your PC), or --check fails on locale differences.
export LC_ALL=C
cd "$(dirname "$0")/.."

DOC=docs/CRYPTO_REVIEW.md
BEGIN='<!-- BEGIN CRYPTO-REVIEW INDEX (generated by scripts/crypto-review.sh, do not edit) -->'
END='<!-- END CRYPTO-REVIEW INDEX -->'

# Every tagged line, as file:line:text.
hits() {
  grep -rn --include='*.rs' --include='*.toml' --include='*.sql' \
      'CRYPTO-REVIEW' \
      crypto-sharecrate data-node hub-node pc-daemon uplink node-sim mobile app database Cargo.toml \
      --exclude-dir=target --exclude-dir=gen --exclude-dir=dist
}

index() {
  echo "$BEGIN"
  echo
  echo "| File | Line | Note |"
  echo "|------|------|------|"
  hits \
    | sort -t: -k1,1 -k2,2n \
    | while IFS=: read -r file line text; do
        note=$(echo "$text" | sed -E 's/.*CRYPTO-REVIEW:? ?//; s/\|/\\|/g; s/^[[:space:]]+//' | cut -c1-140)
        echo "| \`$file\` | $line | $note |"
      done
  echo
  echo "_$(hits | wc -l | tr -d ' ') tagged locations._"
  echo
  echo "$END"
}

new=$(awk -v b="$BEGIN" '$0==b{exit} {print}' "$DOC"; index)

if [[ "${1:-}" == "--check" ]]; then
  if [[ "$new" != "$(cat "$DOC")" ]]; then
    echo "docs/CRYPTO_REVIEW.md is out of date; run ./scripts/crypto-review.sh" >&2
    exit 1
  fi
  echo "crypto review index is up to date"
else
  printf '%s\n' "$new" > "$DOC"
  echo "updated $DOC"
fi
