// Copies Blockly into a TypeScript string so the recipe editor's WebView
// works with no internet (farm Wi-Fi often has none). Runs on `npm install`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
// blockly's "exports" map hides package.json, so find the folder from its main file.
const pkgDir = dirname(require.resolve("blockly"));
const { version } = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));

// blockly.min.js is the UMD build: core, built-in blocks and English text.
// "</script" can't appear inside an inline <script>, so it's escaped.
const js = readFileSync(join(pkgDir, "blockly.min.js"), "utf8").replaceAll("</script", "<\\/script");

const out = join(here, "..", "src", "recipes", "blocklyBundle.generated.ts");
writeFileSync(
  out,
  `// Generated by scripts/bundle-blockly.mjs from blockly@${version}. Do not edit.\n` +
    `export const BLOCKLY_VERSION = ${JSON.stringify(version)};\n` +
    `export const BLOCKLY_JS: string = ${JSON.stringify(js)};\n`,
);
console.log(`bundled blockly@${version} (${Math.round(js.length / 1024)} KB) into ${out}`);
